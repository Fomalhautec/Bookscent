/** 所有预设共用的一段：让解析末尾附一份**机器可读**的词汇表（单词本用它） */
const VOCAB_INSTRUCTION = `

【词汇表：强制格式，必须遵守】
解析的最后必须附一份词汇表，严格按下面的样式。**不要**写成一段话，**不要**用分号把多个词连排。

先单独一行写 [[VOCAB]]，紧接着一行一个词，每行四列、用竖线 | 分隔：
原词|读音|在本句中的意思|word 或 phrase

1. 第一列是原文词形（照原书写，不要翻译）；
2. 第二列是读音（日文写假名；法/德/俄等写音标或拉丁转写）；没有读音写 -；
3. 第三列是这个词**在本句中**的意思，简短，不要再用分号连别的词；
4. 第四列只能是 word 或 phrase；
5. 不管源文本是什么语言，四列格式完全一样；最多 12 条，挑最值得记的；
6. [[VOCAB]] 之后不要再写任何解释文字。
7. **第一列只写词形本身**：不要带释义、不要带读音、不要带括号注释、不要带行尾标点。
   多词短语（如法语 coup d’envoi、mettre fin à）**整条算一条**，绝不按空格拆成几列。
8. 第三列写"在本句中的意思"；需要说明语境时可以写括号（如「生物（本句为生物学意义）」），
   但**不要**把「本句指…」这类话写进第一列。
9. 难句、语法、语感这些内容**不要**写进词汇表 —— 它们各有单独的一节。

示例（源文本为日语）：
[[VOCAB]]
呼び捨て|よびすて|不加敬称直呼姓名|word
同い年|おないどし|同岁|word
さんづけ|さんづけ|在名字后加「さん」的敬称|phrase

示例（源文本为法语）：
[[VOCAB]]
organisme|-|生物、有机体|word
espèce|-|物种|word
élaboré|-|精巧的、复杂的|word`

/** 给一段提示词补上词汇表要求（已经是完整提示词时用） */
export function withVocabInstruction(prompt: string): string {
  if (prompt.includes('[[VOCAB]]')) return prompt
  return `${prompt}${VOCAB_INSTRUCTION}`
}

/**
 * 第二步：**只负责抽词**的那次请求。
 *
 * 为什么拆成两步：以前把"翻译 + 解析 + 结构化词汇表"塞进一次请求，词汇表得附在解析末尾、
 * 用 Markdown 表格写，模型几乎每次都有走样（释义写进词形、多词短语被空格拆开、
 * 难句混进词汇）。把抽词单独做成一次请求、只要它回一个 JSON，格式就稳了 ——
 * 而且这次请求看得到**译文**，判断"本句中的意思"比只看原文更准。
 */
export const VOCAB_EXTRACT_PROMPT = `你是一位词典编纂者。用户会给你一段【原文】和它的【译文】，
请从原文里挑出值得记进单词本的词与固定搭配。

只输出一个 JSON 对象，不要任何解释、不要 Markdown 代码块：
{"words":[{"term":"原词","reading":"读音","meaning":"在本句中的意思","kind":"word"}]}

硬性要求：
1. term 是**原文里出现的词形**，照抄，不翻译、不改写：
   - 多词短语（如法语 coup d’envoi、mettre fin à）**整条作为一条**，绝不按空格拆成几条；
   - 不含释义、不含读音、不含括号注释、不含行尾标点、不含变位说明。
2. reading 是读音：日文写假名，法/德/俄等写音标或拉丁转写；**没有读音就写空字符串 ""**，
   不要拿释义去填这一栏。
3. meaning 用目标语言写"这个词在本句中的意思"，可以带简短语境（如「生物（本句为生物学意义）」）；
   **不要**把「本句指…」这类话写进 term。
4. kind 只能是 word 或 phrase。
5. 只收**原文里真实出现**的词；难句、语法、语感、句式讲解一律不进来。
6. 挑最值得记的，最多 12 条；宁少勿滥，不确定的不要收。`

/** 第二步请求的用户消息：给原文、译文，必要时附上解析（帮助判断语境） */
export function buildVocabExtractMessage(options: {
  source: string
  translation: string
  analysis?: string
  target?: string
}): string {
  const parts = [
    `目标语言：${options.target || '简体中文'}`,
    '',
    '【原文】',
    options.source.trim(),
    '',
    '【译文】',
    options.translation.trim()
  ]
  if (options.analysis && options.analysis.trim()) {
    parts.push('', '【解析（仅供参考语境，不要从中复制说明性文字）】', options.analysis.trim())
  }
  return parts.join('\n')
}